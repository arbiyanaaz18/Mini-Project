
"""
PostgreSQL database connection and schema definitions
for Disaster Resource Tracker.
"""

import os
import psycopg
from psycopg.rows import dict_row

# Neon PostgreSQL connection
DATABASE_URL = os.environ.get("DATABASE_URL")

# Kept for compatibility with existing imports
DB_PATH = None


def get_db_connection(db_path=None):
    """Connect to Neon PostgreSQL."""

    connection_string = db_path or DATABASE_URL

    if not connection_string:
        raise RuntimeError(
            "DATABASE_URL environment variable is not configured."
        )

    return psycopg.connect(
        connection_string,
        row_factory=dict_row,
        sslmode="require"
    )


def create_schema(conn):
    """Create all database tables, constraints and indexes."""

    statements = [

        """
        CREATE TABLE IF NOT EXISTS states (
            state_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
            state_name TEXT NOT NULL UNIQUE
        );
        """,

        """
        CREATE TABLE IF NOT EXISTS districts (
            district_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
            district_name TEXT NOT NULL,
            state_id INTEGER NOT NULL,
            dfsi_score DOUBLE PRECISION,
            population INTEGER NOT NULL DEFAULT 0,
            human_fatality_total INTEGER NOT NULL DEFAULT 0,
            human_injured_total INTEGER NOT NULL DEFAULT 0,
            mean_flood_duration_days DOUBLE PRECISION DEFAULT 0,
            percent_flooded_area DOUBLE PRECISION DEFAULT 0,
            permanent_water_percent DOUBLE PRECISION DEFAULT 0,
            corrected_flooded_area DOUBLE PRECISION DEFAULT 0,
            risk_score DOUBLE PRECISION DEFAULT 0,
            risk_tier TEXT DEFAULT 'Low'
                CHECK (risk_tier IN ('High', 'Moderate', 'Low')),
            FOREIGN KEY (state_id) REFERENCES states(state_id)
                ON DELETE RESTRICT,
            UNIQUE (district_name, state_id)
        );
        """,

        """
        CREATE TABLE IF NOT EXISTS flood_events (
            event_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
            uei TEXT NOT NULL UNIQUE,
            start_date TEXT,
            end_date TEXT,
            duration_days DOUBLE PRECISION DEFAULT 0,
            main_cause TEXT,
            state_name TEXT,
            districts_mentioned TEXT,
            human_fatality INTEGER DEFAULT 0,
            human_injured INTEGER DEFAULT 0,
            human_displaced TEXT,
            animal_fatality TEXT,
            description TEXT,
            extent_of_damage TEXT,
            event_source TEXT,
            district_lgd_codes TEXT,
            state_codes TEXT
        );
        """,

        """
        CREATE TABLE IF NOT EXISTS annual_impact (
            id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
            year TEXT NOT NULL UNIQUE,
            lives_lost INTEGER NOT NULL,
            cattle_lost INTEGER NOT NULL,
            houses_damaged INTEGER NOT NULL,
            cropped_area_affected_lakh_ha DOUBLE PRECISION NOT NULL
        );
        """,

        """
        CREATE TABLE IF NOT EXISTS resources (
            resource_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
            resource_name TEXT NOT NULL,
            category TEXT NOT NULL,
            unit TEXT NOT NULL,
            total_quantity INTEGER NOT NULL CHECK (total_quantity >= 0),
            available_quantity INTEGER NOT NULL CHECK (available_quantity >= 0),
            allocated_quantity INTEGER NOT NULL DEFAULT 0
                CHECK (allocated_quantity >= 0),
            warehouse_location TEXT NOT NULL,
            status TEXT NOT NULL DEFAULT 'Available'
                CHECK (status IN ('Available', 'Low Stock', 'Critical')),
            is_demo_data INTEGER NOT NULL DEFAULT 1
                CHECK (is_demo_data IN (0, 1))
        );
        """,

        """
        CREATE TABLE IF NOT EXISTS resource_requests (
            request_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
            district_id INTEGER NOT NULL,
            resource_id INTEGER NOT NULL,
            requester_name TEXT NOT NULL,
            requester_contact TEXT NOT NULL,
            quantity_requested INTEGER NOT NULL CHECK (quantity_requested > 0),
            urgency_level TEXT NOT NULL
                CHECK (urgency_level IN ('Critical', 'High', 'Medium', 'Low')),
            calculated_priority_score DOUBLE PRECISION NOT NULL DEFAULT 0,
            status TEXT NOT NULL DEFAULT 'Pending'
                CHECK (status IN ('Pending', 'Approved', 'Rejected', 'Dispatched')),
            reason_notes TEXT,
            requested_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
            reviewed_at TIMESTAMP,
            reviewed_by TEXT,
            FOREIGN KEY (district_id) REFERENCES districts(district_id)
                ON DELETE CASCADE,
            FOREIGN KEY (resource_id) REFERENCES resources(resource_id)
                ON DELETE RESTRICT
        );
        """,

        """
        CREATE TABLE IF NOT EXISTS reported_incidents (
            incident_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
            district_id INTEGER,
            reporter_name TEXT NOT NULL,
            reporter_phone TEXT NOT NULL,
            disaster_type TEXT NOT NULL DEFAULT 'Flood',
            severity_level TEXT NOT NULL
                CHECK (severity_level IN ('Critical', 'Severe', 'Moderate', 'Minor')),
            estimated_affected_people INTEGER DEFAULT 0
                CHECK (estimated_affected_people >= 0),
            description TEXT NOT NULL,
            reported_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
            verification_status TEXT NOT NULL DEFAULT 'Unverified'
                CHECK (verification_status IN ('Unverified', 'Verified', 'Resolved')),
            FOREIGN KEY (district_id) REFERENCES districts(district_id)
                ON DELETE SET NULL
        );
        """,

        "CREATE INDEX IF NOT EXISTS idx_districts_state ON districts(state_id);",
        "CREATE INDEX IF NOT EXISTS idx_districts_risk ON districts(risk_tier);",
        "CREATE INDEX IF NOT EXISTS idx_events_state ON flood_events(state_name);",
        "CREATE INDEX IF NOT EXISTS idx_events_start ON flood_events(start_date);",
        "CREATE INDEX IF NOT EXISTS idx_requests_status ON resource_requests(status);",
        "CREATE INDEX IF NOT EXISTS idx_requests_district ON resource_requests(district_id);",
        "CREATE INDEX IF NOT EXISTS idx_requests_resource ON resource_requests(resource_id);",
        "CREATE INDEX IF NOT EXISTS idx_incidents_district ON reported_incidents(district_id);",

        """
        CREATE UNIQUE INDEX IF NOT EXISTS idx_states_name_lower
        ON states (LOWER(state_name));
        """,

        """
        CREATE UNIQUE INDEX IF NOT EXISTS idx_districts_name_state_lower
        ON districts (LOWER(district_name), state_id);
        """
    ]

    with conn.cursor() as cursor:
        for statement in statements:
            cursor.execute(statement)

    conn.commit()
